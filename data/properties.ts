/**
 * Filter properties helper function
 */
export function filterProperties(
  properties: Property[],
  filters: {
    listingType?: string;
    location?: string;
    category?: string;
    minPrice?: number;
    maxPrice?: number;
    bedrooms?: number | string;
    searchQuery?: string;
    sortBy?: string;
  }
): Property[] {
  return properties.filter((p) => {
    // Listing Type
    if (filters.listingType && filters.listingType !== "all") {
      if (p.listingType !== filters.listingType) return false;
    }

    // Location
    if (filters.location && filters.location !== "all") {
      const matchRegion = p.location.region.toLowerCase() === filters.location.toLowerCase();
      const matchCity = p.location.city.toLowerCase().includes(filters.location.toLowerCase());
      const matchNeighborhood = p.location.neighborhood.toLowerCase().includes(filters.location.toLowerCase());
      if (!matchRegion && !matchCity && !matchNeighborhood) return false;
    }

    // Category
    if (filters.category && filters.category !== "all") {
      if (p.category !== filters.category) return false;
    }

    // Price
    if (filters.minPrice && p.priceGBP < filters.minPrice) return false;
    if (filters.maxPrice && p.priceGBP > filters.maxPrice) return false;

    // Bedrooms
    if (filters.bedrooms && filters.bedrooms !== "any") {
      const minBeds = Number(filters.bedrooms);
      if (p.specs.bedrooms < minBeds) return false;
    }

    // Search Query (Text)
    if (filters.searchQuery && filters.searchQuery.trim() !== "") {
      const query = filters.searchQuery.toLowerCase().trim();
      const text = `${p.title} ${p.subtitle} ${p.location.neighborhood} ${p.location.city} ${p.location.postcodeArea} ${p.category} ${p.tagline}`.toLowerCase();
      if (!text.includes(query)) return false;
    }

    return true;
  }).sort((a, b) => {
    if (filters.sortBy === "price-asc") {
      return a.priceGBP - b.priceGBP;
    }
    if (filters.sortBy === "price-desc") {
      return b.priceGBP - a.priceGBP;
    }
    if (filters.sortBy === "bedrooms") {
      return b.specs.bedrooms - a.specs.bedrooms;
    }
    if (filters.sortBy === "newest") {
      return new Date(b.dateListed).getTime() - new Date(a.dateListed).getTime();
    }
    // Default: featured first, then user supplied first
    if (a.isUserSuppliedImage && !b.isUserSuppliedImage) return -1;
    if (!a.isUserSuppliedImage && b.isUserSuppliedImage) return 1;
    if (a.isFeatured && !b.isFeatured) return -1;
    if (!a.isFeatured && b.isFeatured) return 1;
    return 0;
  });
}
